context.window.phoneLinkNavigate('calls');
context.window.phoneLinkNavigate('clipboard');
assert.match(element('#view').innerHTML,/clipboard-text/);
assert(messages>=2,'Snapshots use postMessage across opaque file origins');
console.log('Calls → Photos and Calls → Clipboard remain responsive across opaque frame origins.');
